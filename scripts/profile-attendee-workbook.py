"""Profile the attendee workbook and compute reference metrics.

Usage: python3 scripts/profile-attendee-workbook.py <path-to-Attendee Dataset.xlsx>

Writes:
  docs/data-profile.md                 human-readable profile and mapping
  tests/fixtures/expected-metrics.json reference numbers the TypeScript analytics are tested against

The rules come from the workbook's own "Read me" and "Field guide" sheets:
  * exact repeated source IDs are import copies and count once
  * only admitted + verified check-ins establish attendance
  * attendee targets apply to distinct external people
  * the latest registration-history version per registration_id is its state
"""
import json
import sys
from pathlib import Path

import pandas as pd

SRC = Path(sys.argv[1] if len(sys.argv) > 1 else "data/Attendee Dataset.xlsx")
ROOT = Path(__file__).resolve().parent.parent

ID_COLS = {
    "Campaigns": "campaign_id",
    "Daily Marketing": "activity_id",
    "People": "person_id",
    "Interest and Engagement": "interaction_id",
    "Registrations": "registration_id",
    "Registration History": "history_id",
    "Check-ins": "event_id",
}

xl = pd.ExcelFile(SRC)
sheets = {s: xl.parse(s) for s in xl.sheet_names}

lines = ["# Attendee workbook: data profile", "",
         f"Source file: `{SRC.name}`. Generated by `scripts/profile-attendee-workbook.py`.", "",
         "## Sheets", "",
         "| Sheet | Rows | Columns | Stable ID | Duplicate ID rows | Distinct IDs |",
         "|---|---:|---:|---|---:|---:|"]
dup_summary = {}
for name, df in sheets.items():
    idc = ID_COLS.get(name)
    dups = int(df[idc].duplicated().sum()) if idc else 0
    distinct = int(df[idc].nunique()) if idc else "–"
    dup_summary[name] = dups
    lines.append(f"| {name} | {len(df)} | {len(df.columns)} | {idc or '–'} | {dups} | {distinct} |")

lines += ["", "## Columns", ""]
for name, df in sheets.items():
    if name in ("Read me", "Field guide"):
        continue
    lines += [f"### {name}", "", "| Column | Type | Nulls | Distinct | Example values |", "|---|---|---:|---:|---|"]
    for c in df.columns:
        col = df[c]
        ex = ", ".join(str(v) for v in col.dropna().astype(str).unique()[:3])
        lines.append(f"| `{c}` | {col.dtype} | {int(col.isna().sum())} | {int(col.nunique())} | {ex[:90]} |")
    lines.append("")

# ---- reference metrics -------------------------------------------------------
dedup = {n: (df.drop_duplicates(ID_COLS[n]) if n in ID_COLS else df) for n, df in sheets.items()}
people = dedup["People"]
ext = set(people.loc[people.person_type == "external", "person_id"])
ck = dedup["Check-ins"]
ver = ck[(ck.result == "admitted") & (ck.verification == "verified")]
ver_ext = ver[ver.person_id.isin(ext)]
attendees = set(ver_ext.person_id)
by_day = ver_ext.groupby(ver_ext.occurred_at.dt.strftime("%Y-%m-%d")).person_id.nunique().to_dict()
days_per_person = ver_ext.groupby("person_id").occurred_at.apply(lambda s: s.dt.date.nunique())

reg = dedup["Registrations"]
reg_ext = reg[reg.person_id.isin(ext)]
rh = dedup["Registration History"]
latest = rh.sort_values(["effective_at", "history_id"]).groupby("registration_id").tail(1)
latest_ext = latest[latest.person_id.isin(ext)]

dm = dedup["Daily Marketing"]
camps = dedup["Campaigns"]
targets = dedup["Targets"].sort_values("effective_at")

per_campaign = {}
for _, c in camps.iterrows():
    cid = c.campaign_id
    r = reg_ext[reg_ext.campaign_id == cid]
    att = len(set(r.person_id) & attendees)
    spend = int(dm.loc[dm.campaign_id == cid, "marketing_spend_inr"].sum())
    per_campaign[cid] = {
        "name": c.campaign_name,
        "spend_inr": spend,
        "registered_people": int(r.person_id.nunique()),
        "verified_attendees_from_registrations": att,
        "show_rate": round(att / r.person_id.nunique(), 4) if len(r) else None,
        "first_touch_identified_people": int(people[(people.person_type == "external") & (people.first_campaign_id == cid)].person_id.nunique()),
    }

walk_ins = attendees - set(reg_ext.person_id)
expected = {
    "dedup_rows_removed": dup_summary,
    "people_total": int(len(people)),
    "people_by_type": people.person_type.value_counts().to_dict(),
    "identified_external_people": len(ext),
    "registrations_total": int(len(reg)),
    "registered_external_people": int(reg_ext.person_id.nunique()),
    "latest_status_external": latest_ext.status.value_counts().to_dict(),
    "unique_verified_external_attendees": len(attendees),
    "verified_external_attendees_by_day": by_day,
    "attendees_both_days": int((days_per_person == 2).sum()),
    "verified_admission_rows_external": int(len(ver_ext)),
    "walk_in_attendees_without_registration": len(walk_ins),
    "checkin_results": ck.result.value_counts().to_dict(),
    "marketing_spend_total_inr": int(dm.marketing_spend_inr.sum()),
    "latest_target": {k: (int(v) if isinstance(v, (int,)) or hasattr(v, "item") else str(v)) for k, v in targets.iloc[-1].drop("effective_at").items()},
    "per_campaign": per_campaign,
}
for k, v in list(expected["latest_target"].items()):
    try:
        expected["latest_target"][k] = int(v)
    except (TypeError, ValueError):
        pass

lines += ["## Reference metrics (rules from the workbook's own field guide)", "",
          f"* Unique verified external attendees: **{len(attendees)}** (admitted + verified check-ins, external people, deduplicated by person).",
          f"* By day: {by_day}; attended both days: {expected['attendees_both_days']}.",
          f"* Identified external people: {len(ext)}; registered external people: {expected['registered_external_people']}.",
          f"* Latest registration status (external): {expected['latest_status_external']}.",
          f"* Net marketing spend: ₹{expected['marketing_spend_total_inr']:,} (includes {int((dm.marketing_spend_inr < 0).sum())} vendor-credit rows).",
          f"* Verified attendees without any registration (walk-ins): {len(walk_ins)}.",
          "",
          "## What the workbook does not contain",
          "",
          "* No venue capacity. Capacity must be configured by an admin; until then the app reports it as unconfirmed.",
          "* Reach, impressions, clicks, sessions and form starts are anonymous daily counts. They cannot be joined to people, so reach→registration conversion per person is not computable.",
          "* No task, owner workload or budget-commitment data. Those modules start from seeded demo records that are labelled as such.",
          "* No experiment or control-group data, so incremental lift cannot be calculated from this workbook.",
          "* Owners are team IDs (T03–T06) with names; there are no roles or permissions in the source.",
          ""]

(ROOT / "docs").mkdir(exist_ok=True)
(ROOT / "docs" / "data-profile.md").write_text("\n".join(lines))
(ROOT / "tests" / "fixtures").mkdir(parents=True, exist_ok=True)
(ROOT / "tests" / "fixtures" / "expected-metrics.json").write_text(json.dumps(expected, indent=2, default=str))
print(json.dumps({k: expected[k] for k in ["unique_verified_external_attendees", "identified_external_people", "registered_external_people", "marketing_spend_total_inr", "attendees_both_days", "walk_in_attendees_without_registration"]}, indent=1))
